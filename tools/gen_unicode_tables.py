#!/usr/bin/env python3
"""Generate compact Unicode property ranges used by the Cipher text stack.

Source of truth: Python's unicodedata (Unicode 16.0.0 on this machine).
Emits `src/ui/text/unicode_tables.zig`; regenerate with this script when the
toolchain's Unicode version changes. No runtime dependency, no build step.
"""
import sys, unicodedata

OUT = sys.argv[1] if len(sys.argv) > 1 else "src/ui/text/unicode_tables.zig"

def ranges_of(pred):
    out = []
    start = None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

def cat(cp):
    return unicodedata.category(chr(cp))

# Grapheme_Cluster_Break=Extend approximation: Grapheme_Extend (Mn/Me),
# ZWNJ/ZWJ (Cf), variation selectors, emoji modifiers and tag characters.
def is_extend(cp):
    if cp in (0x200C, 0x200D):
        return True
    if 0x1F3FB <= cp <= 0x1F3FF:      # emoji skin tone modifiers
        return True
    if 0xE0020 <= cp <= 0xE007F:      # tag characters (subdivision flags)
        return True
    return cat(cp) in ("Mn", "Me")

# SpacingMark approximation: Mc. (Prepend is not modelled; see docs.)
def is_spacing_mark(cp):
    return cat(cp) == "Mc"

ext = ranges_of(is_extend)
mc = ranges_of(is_spacing_mark)

def emit(name, rs):
    lines = [f"pub const {name} = [_][2]u21{{"]
    for a, b in rs:
        lines.append(f"    .{{ 0x{a:04X}, 0x{b:04X} }},")
    lines.append("};")
    return "\n".join(lines)

hdr = f"""//! Generated by tools/gen_unicode_tables.py — do not edit by hand.
//! Unicode {unicodedata.unidata_version} property ranges consumed by
//! `src/text/grapheme.zig` (extended grapheme cluster segmentation).
//!
//! `extend` = Grapheme_Extend (Mn/Me) + ZWNJ/ZWJ + variation selectors +
//! emoji modifiers + tag characters. `spacing_mark` = Mc, kept separate
//! because a spacing mark attaches to the preceding cluster.
"""
with open(OUT, "w") as f:
    f.write(hdr + "\n")
    f.write(emit("extend", ext) + "\n\n")
    f.write(emit("spacing_mark", mc) + "\n\n")
    f.write("""/// Binary search a sorted inclusive range table.
pub fn inRanges(ranges: []const [2]u21, cp: u21) bool {
    var lo: usize = 0;
    var hi: usize = ranges.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        const r = ranges[mid];
        if (cp < r[0]) hi = mid else if (cp > r[1]) lo = mid + 1 else return true;
    }
    return false;
}
""")
print(f"wrote {OUT}: extend={len(ext)} spacing_mark={len(mc)} unicode={unicodedata.unidata_version}")
