#!/usr/bin/env python3
"""Generate Zig wl_interface tables from the installed wayland-protocols XML.

Emits the core interfaces (wayland.xml), xdg-shell (xdg-shell.xml), and
text-input-unstable-v3 (the IME boundary) that the Cipher runtime needs. Everything is a static definition — no link-time
externs, no wayland-scanner. Enums stay uint; signatures follow the spec.

usage: gen_wayland_tables.py <wayland.xml> <xdg-shell.xml> <text-input-v3.xml> <out.zig>
"""
import sys, xml.etree.ElementTree as ET

CORE_XML, XDG_XML, TI_XML, OUT = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]

TYPE = {'int': 'i', 'uint': 'u', 'fixed': 'f', 'string': 's', 'object': 'o',
        'new_id': 'n', 'array': 'a', 'fd': 'h'}

def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')

def sig(m):
    return ''.join(TYPE[a.get('type')] for a in m.findall('arg'))

def types_of(m, emitted, parent):
    args = []
    for a in m.findall('arg'):
        t = a.get('type')
        iface = a.get('interface', '')
        self_ref = iface == parent
        # Zig value dependency: nulls for self-references (C's extern cycles
        # cannot exist here). 'n' without interface expands to sun with NULL
        # types; marshalling uses the fixed interface param anyway.
        if t in ('new_id', 'object') and iface and iface in emitted and not self_ref:
            args.append('&%s_interface' % iface)
        else:
            args.append('null')
    return ', '.join(args)

def message_pair(m, emitted, parent):
    """Return (signature, [types...]) mirroring wayland-scanner exactly:
    - leading since digit when since > 1
    - allow-null object/string args get a '?' prefix
    - new_id without interface expands to 'sun' with NULL types entries
    - new_id with interface and object args get &iface in types (self-refs nulled)
    - enum keeps the base letter"""
    sig = ''
    ty = []
    since = m.get('since')
    if since and since != '1':
        sig += since
    for a in m.findall('arg'):
        t = a.get('type')
        iface = a.get('interface', '')
        letter = TYPE[t]
        if t == 'new_id' and not iface:
            sig += 'sun'
            ty += ['null', 'null', 'null']
            continue
        if a.get('allow-null') == 'true':
            sig += '?' + letter
        else:
            sig += letter
        self_ref = iface == parent
        if t in ('new_id', 'object') and iface and iface in emitted and not self_ref:
            ty.append('&%s_interface' % iface)
        elif t == 'new_id' and iface and iface in emitted and self_ref:
            ty.append('null')
        else:
            ty.append('null')
    return sig, ty

def sig(m):
    return ''.join(TYPE[a.get('type')] for a in m.findall('arg'))

CORE_EMIT = ['wl_display', 'wl_registry', 'wl_callback', 'wl_compositor', 'wl_region',
             'wl_surface', 'wl_shm', 'wl_shm_pool', 'wl_buffer',
             'wl_seat', 'wl_keyboard', 'wl_pointer', 'wl_output',
             'wl_subcompositor', 'wl_subsurface',
             'wl_data_device_manager', 'wl_data_device', 'wl_data_offer', 'wl_data_source']
XDG_EMIT = ['xdg_wm_base', 'xdg_positioner', 'xdg_popup', 'xdg_surface', 'xdg_toplevel']
# text-input-unstable-v3 is the IME boundary: the compositor acts as input method.
TI_EMIT = ['zwp_text_input_manager_v3', 'zwp_text_input_v3']

core = {i.get('name'): i for i in ET.parse(CORE_XML).getroot().findall('interface')}
xdg = {i.get('name'): i for i in ET.parse(XDG_XML).getroot().findall('interface')}
ti = {i.get('name'): i for i in ET.parse(TI_XML).getroot().findall('interface')}

missing = ([n for n in CORE_EMIT if n not in core] + [n for n in XDG_EMIT if n not in xdg] +
           [n for n in TI_EMIT if n not in ti])
if missing:
    sys.exit('missing interfaces: %s' % missing)

EMIT = CORE_EMIT + XDG_EMIT + TI_EMIT
emitted = set(EMIT)

with open(OUT, 'w') as f:
    w = f.write
    w('''//! Generated by tools/gen_wayland_tables.py from the installed
//! wayland.xml, xdg-shell.xml and text-input-unstable-v3.xml. Do not edit by hand — regenerate.
//! Static wl_interface tables for every interface Cipher references.
const std = @import("std");

pub const wl_message = extern struct {
    name: [*:0]const u8,
    signature: [*:0]const u8,
    types: ?[*]const ?*const wl_interface,
};

pub const wl_interface = extern struct {
    name: [*:0]const u8,
    version: i32,
    method_count: u32,
    methods: ?[*]const wl_message,
    event_count: u32,
    events: ?[*]const wl_message,
};

''')
    def table(name, iface):
        reqs = [e for e in iface if e.tag == 'request']
        evts = [e for e in iface if e.tag == 'event']
        w('const %s = struct {\n' % name)
        w('    const methods = [_]wl_message{\n')
        for m in reqs:
            s, ty = message_pair(m, emitted, name)
            w('        .{ .name = "%s", .signature = "%s", .types = &.{%s} },\n' %
              (esc(m.get('name')), s, ', '.join(ty)))
        w('    };\n')
        w('    const events = [_]wl_message{\n')
        for m in evts:
            s, ty = message_pair(m, emitted, name)
            w('        .{ .name = "%s", .signature = "%s", .types = &.{%s} },\n' %
              (esc(m.get('name')), s, ', '.join(ty)))
        w('    };\n')
        w('};\n\n')
        w('pub const %s_interface = wl_interface{ .name = "%s", .version = %s, .method_count = %d, .methods = &%s.methods, .event_count = %d, .events = &%s.events };\n\n' %
          (name, name, iface.get('version'), len(reqs), name, len(evts), name))
    for name in CORE_EMIT:
        table(name, core[name])
    for name in XDG_EMIT:
        table(name, xdg[name])
    for name in TI_EMIT:
        table(name, ti[name])
