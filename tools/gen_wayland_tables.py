#!/usr/bin/env python3
"""Generate Zig wl_interface tables from the installed wayland-protocols XML.

Emits BOTH the core interfaces (wayland.xml) and xdg-shell (xdg-shell.xml) the
Cipher runtime needs. Everything is a static definition — no link-time
externs, no wayland-scanner. Enums stay uint; signatures follow the spec.

usage: gen_wayland_tables.py <wayland.xml> <xdg-shell.xml> <out.zig>
"""
import sys, xml.etree.ElementTree as ET

CORE_XML, XDG_XML, OUT = sys.argv[1], sys.argv[2], sys.argv[3]

TYPE = {'int': 'i', 'uint': 'u', 'fixed': 'f', 'string': 's', 'object': 'o',
        'new_id': 'n', 'array': 'a', 'fd': 'h'}

def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')

def sig(m):
    return ''.join(TYPE[a.get('type')] for a in m.findall('arg'))

def types_of(m, emitted, parent):
    args = []
    for a in m.findall('arg'):
        t = a.get('type')
        iface = a.get('interface', '')
        # Self-references would make the wl_interface value depend on its own
        # methods table (dependency loop in Zig); the types array is not used
        # by Cipher's marshalling path, so null them out.
        if t in ('new_id', 'object') and iface and iface in emitted and iface != parent:
            args.append('&%s_interface' % iface)
        else:
            args.append('null')
    return ', '.join(args)

CORE_EMIT = ['wl_display', 'wl_registry', 'wl_callback', 'wl_compositor', 'wl_region',
             'wl_surface', 'wl_shm', 'wl_shm_pool', 'wl_buffer',
             'wl_seat', 'wl_keyboard', 'wl_pointer', 'wl_output',
             'wl_subcompositor', 'wl_subsurface',
             'wl_data_device_manager', 'wl_data_device', 'wl_data_offer', 'wl_data_source']
XDG_EMIT = ['xdg_wm_base', 'xdg_positioner', 'xdg_popup', 'xdg_surface', 'xdg_toplevel']

core = {i.get('name'): i for i in ET.parse(CORE_XML).getroot().findall('interface')}
xdg = {i.get('name'): i for i in ET.parse(XDG_XML).getroot().findall('interface')}

missing = [n for n in CORE_EMIT if n not in core] + [n for n in XDG_EMIT if n not in xdg]
if missing:
    sys.exit('missing interfaces: %s' % missing)

EMIT = CORE_EMIT + XDG_EMIT
emitted = set(EMIT)

with open(OUT, 'w') as f:
    w = f.write
    w('''//! Generated by tools/gen_wayland_tables.py from the installed
//! wayland.xml and xdg-shell.xml. Do not edit by hand — regenerate.
//! Static wl_interface tables for every interface Cipher references.
const std = @import("std");

pub const wl_message = extern struct {
    name: [*:0]const u8,
    signature: [*:0]const u8,
    types: ?[*]const ?*const wl_interface,
};

pub const wl_interface = extern struct {
    name: [*:0]const u8,
    version: i32,
    method_count: u32,
    methods: ?[*]const wl_message,
    event_count: u32,
    events: ?[*]const wl_message,
};

''')
    def table(name, iface):
        reqs = [e for e in iface if e.tag == 'request']
        evts = [e for e in iface if e.tag == 'event']
        w('const %s = struct {\n' % name)
        w('    const methods = [_]wl_message{\n')
        for m in reqs:
            w('        .{ .name = "%s", .signature = "%s", .types = &.{%s} },\n' %
              (esc(m.get('name')), sig(m), types_of(m, emitted, name)))
        w('    };\n')
        w('    const events = [_]wl_message{\n')
        for m in evts:
            w('        .{ .name = "%s", .signature = "%s", .types = &.{%s} },\n' %
              (esc(m.get('name')), sig(m), types_of(m, emitted, name)))
        w('    };\n')
        w('};\n\n')
        w('pub const %s_interface = wl_interface{ .name = "%s", .version = %s, .method_count = %d, .methods = &%s.methods, .event_count = %d, .events = &%s.events };\n\n' %
          (name, name, iface.get('version'), len(reqs), name, len(evts), name))
    for name in CORE_EMIT:
        table(name, core[name])
    for name in XDG_EMIT:
        table(name, xdg[name])
