#!/usr/bin/env python3
"""Generate Zig wl_interface tables from wayland-protocols xdg-shell XML.

Only xdg_wm_base / xdg_surface / xdg_toplevel are emitted. Message opcodes are
positional *within each kind* (requests then events), matching the spec.

usage: gen_xdg_shell.py <xdg-shell.xml> <out.zig>
"""
import sys, xml.etree.ElementTree as ET

XML_PATH, OUT_PATH = sys.argv[1], sys.argv[2]

TYPE = {'int': 'i', 'uint': 'u', 'fixed': 'f', 'string': 's', 'object': 'o',
        'new_id': 'n', 'array': 'a', 'fd': 'h'}
# note: enum counts as uint per spec when type=uint with enum= attribute

def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')

def sig(m):
    return ''.join(TYPE[a.get('type')] for a in m.findall('arg'))

root = ET.parse(XML_PATH).getroot()
parent_of = {}
iface = {}
for i in root.findall('interface'):
    iface[i.get('name')] = i
    for m in i:  # attach parent for resolving
        pass

KEEP = ['xdg_wm_base', 'xdg_surface', 'xdg_toplevel']
referenced = set()
for name in KEEP:
    for m in iface[name]:
        for a in m.findall('arg'):
            iface_attr = a.get('interface', '')
            if iface_attr:
                referenced.add(iface_attr)
EMIT = KEEP + sorted(i for i in referenced if i not in KEEP and not i.startswith('wl_'))

# names of interfaces to reference
core_refs = {}
for name in EMIT:
    for m in iface[name]:
        for a in m.findall('arg'):
            iface_attr = a.get('interface', '')
            if iface_attr:
                core_refs[iface_attr] = None

with open(OUT_PATH, 'w') as f:
    w = f.write
    w('''//! Generated by tools/gen_xdg_shell.py from wayland-protocols xdg-shell.xml.
//! Minimal subset needed by Cipher: xdg_wm_base, xdg_surface, xdg_toplevel
//! and the core interfaces they reference (wl_surface, wl_seat, wl_output).
const std = @import("std");

pub const wl_message = extern struct {
    name: [*:0]const u8,
    signature: [*:0]const u8,
    types: ?[*]const ?*const wl_interface,
};

pub const wl_interface = extern struct {
    name: [*:0]const u8,
    version: i32,
    method_count: u32,
    methods: ?[*]const wl_message,
    event_count: u32,
    events: ?[*]const wl_message,
};

''')
    for ext in sorted(core_refs):
        w('extern pub const %s_interface: wl_interface;\n' % ext)
    w('\n')

    def emit_table(name):
        i = iface[name]
        reqs = i.findall('request')
        evts = i.findall('event')
        parts_req = []
        for idx, m in enumerate(reqs + evts):
            args = []
            for j, a in enumerate(m.findall('arg')):
                t = a.get('type')
                iface_attr = a.get('interface', '')
                if t == 'new_id' and iface_attr:
                    args.append('&%s_interface' % iface_attr)
                elif t == 'object' and iface_attr:
                    args.append('&%s_interface' % iface_attr)
                else:
                    args.append('null')
            parts_req.append((esc(m.get('name')), sig(m), args))
        w('const %s = struct {\n' % name)
        w('    pub const methods = [_]wl_message{\n')
        for idx, m in enumerate(reqs):
            nm = esc(m.get('name')); sg = sig(m)
            args = []
            for a in m.findall('arg'):
                t = a.get('type'); iface_attr = a.get('interface', '')
                if iface_attr: args.append('&%s_interface' % iface_attr)
                else: args.append('null')
            w('        .{ .name = "%s", .signature = "%s", .types = &.{%s} },\n' % (nm, sg, ', '.join(args)))
        w('    };\n')
        w('    pub const events = [_]wl_message{\n')
        for idx, m in enumerate(evts):
            nm = esc(m.get('name')); sg = sig(m)
            args = []
            for a in m.findall('arg'):
                t = a.get('type'); iface_attr = a.get('interface', '')
                if iface_attr: args.append('&%s_interface' % iface_attr)
                else: args.append('null')
            w('        .{ .name = "%s", .signature = "%s", .types = &.{%s} },\n' % (nm, sg, ', '.join(args)))
        w('    };\n')
        w('};\n\n')
        w('pub const %s_interface = wl_interface{ .name = "%s", .version = 7, .method_count = %d, .methods = &%s.methods, .event_count = %d, .events = &%s.events };\n\n' % (name, name, len(reqs), name, len(evts), name))

    for name in KEEP:
        emit_table(name)
